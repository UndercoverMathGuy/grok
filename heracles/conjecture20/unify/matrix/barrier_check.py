"""Evaluate the chain relaxation (mode 'free') at the Disproof's barrier point (p=3, n=3, b=2) and polish it.
Barrier field (in the Disproof's convention): Phi = 1 except Phi(2,2,2) = 1+27 kappa e^{-i pi/3}, Phi(1,1,1) = 1+27 kappa e^{i pi/3},
with own modes generated by three slot-symmetric atoms.  Our field convention is the complex conjugate (characters 2j1_T),
so we take Phi_ours = conj(Phi_barrier) evaluated at the same points; margins and costs are conjugation invariant.
"""
import numpy as np, itertools
from relax2 import Relax2

p, n, b = 3, 3, 2.0
s = (n + 1) / b
R = Relax2(p, n, s, 'free', S=[1])
kap = 0.27306
Phi = np.ones(R.N, dtype=complex)
for i, x in enumerate(R.X):
    if tuple(x) == (2, 2, 2):
        Phi[i] = 1 + 27 * kap * np.exp(-1j * np.pi / 3)
    if tuple(x) == (1, 1, 1):
        Phi[i] = 1 + 27 * kap * np.exp(1j * np.pi / 3)
for conjugate in [False, True]:
    P = np.conj(Phi) if conjugate else Phi
    # coefficients: phi(chi) = mean_x Phi(x) rho^{-chi x}
    phi = {1: (np.conj(R.E).T @ P) / R.N}
    U = {1: np.zeros(len(R.up), dtype=complex)}
    h = R.margin_exact(phi)
    # optimise U only (free mirror completion) by local search from several completions
    from scipy.optimize import minimize
    H0 = R.chain(1, phi, U)
    best = np.inf
    rng = np.random.default_rng(0)
    for trial in range(30):
        if trial == 0:
            u0 = np.zeros(len(R.up), dtype=complex)
        elif trial == 1:
            u0 = np.array([np.conj(H0[tp, t]) for (t, tp) in R.up])  # Hermitian completion
        else:
            u0 = rng.normal(size=len(R.up)) + 1j * rng.normal(size=len(R.up))
        def f(w):
            Uc = {1: w[0::2] + 1j * w[1::2]}
            c, G = R.cost(phi, Uc, grad=True)
            g = np.zeros_like(w)
            for k, (t, tp) in enumerate(R.up):
                g[2 * k] = G[1][t, tp].real; g[2 * k + 1] = G[1][t, tp].imag
            return c, g
        w0 = np.ravel(np.column_stack([u0.real, u0.imag]))
        res = minimize(f, w0, jac=True, method='L-BFGS-B')
        best = min(best, res.fun)
    q = R.nu ** (-R.r) * best
    ratio = h / (R.nu ** (1 - R.s) * R.G * q ** R.s)
    print(f"conj={conjugate}: margin h={h:.6f} (kappa_min*cm), own coeffs:",
          np.round([phi[1][R.own_idx[1][T]] for T in R.Ts], 4))
    print(f"   best chain cost sum sigma^r = {best:.6f}, q = {q:.6f}, ratio = {ratio:.6f}  (atomic barrier ratio 1.0316)")
