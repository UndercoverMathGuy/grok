"""Atomic free relaxation R_atom(S'): a relaxation of the margin problem over ALL networks.

Own modes of feature j are generated by atoms (beta_ij, xi_ij) exactly as in any network (paper Lemma 6, any inputs);
cost = sum_{i,j} |beta_ij|^r (single-neuron budget).  Every other Fourier coefficient of every field Phi_j (j in S') is
FREE (partner, riding, stray outputs, DC, mixed modes).  Margin = exact LP.  Ratio = h/(nu^{1-s} Gamma_s(p) Q^s).
Since every network is feasible (with its own non-own modes), R_atom(F) >= gamma*/gamma_IF.
Usage: python freeatoms.py p n b restarts seed [S' ...]   (default S' = F)
"""
import sys, time, itertools
import numpy as np
from scipy.optimize import minimize
from mrel import Model, subsets
sys.path.insert(0, '/home/user/grok/heracles/conjecture20/mechanism_scripts')
from prog import solve as prog_solve


class FA:
    def __init__(self, p, n, s, S, natoms):
        self.p, self.n, self.s, self.r, self.nu = p, n, s, 1 / s, n + 1
        self.S = list(S)
        self.M = Model(p, n, self.S, mode='free', s=s)
        self.Ts = subsets(n)
        self.G, self.ystar, _ = prog_solve(p, s, restarts=8)
        self.na = dict(natoms)  # j -> number of atoms
        # mask matrix: own(T) = sum_i beta_i prod_{t in T} xi_it
        self.Tmask = np.array([[1 if t in T else 0 for t in range(n)] for T in self.Ts])  # 2^n x n

    def unpack(self, th):
        out = {}; k = 0
        for j in self.S:
            m = self.na[j]
            br = th[k:k + m]; bi = th[k + m:k + 2 * m]; k += 2 * m
            ph = th[k:k + m * self.n].reshape(m, self.n); k += m * self.n
            out[j] = (br + 1j * bi, ph)
        return out

    def own(self, beta, ph):
        # own field coefficient a(T) = conj( sum_i beta_i exp(i sum_{t in T} ph_it) )
        E = np.exp(1j * (self.Tmask @ ph.T))  # 2^n x m
        return np.conj(E @ beta), E

    def ratio_and_grad(self, th):
        at = self.unpack(th)
        a = {}; Es = {}
        for j in self.S:
            v, E = self.own(*at[j])
            a[j] = {T: v[i] for i, T in enumerate(self.Ts)}
            Es[j] = E
        h, gh = self.M.margin(a)
        Q = sum(np.sum(np.abs(at[j][0]) ** self.r) for j in self.S)
        if h is None:
            return None
        ratio = h / (self.nu ** (1 - self.s) * self.G * Q ** self.s)
        # gradient of F = -log h + s log Q  (only meaningful for h > 0)
        g = np.zeros_like(th); k = 0
        for j in self.S:
            beta, ph = at[j]; m = len(beta); E = Es[j]
            gam = np.array([gh.get((j, T), 0j) for T in self.Ts])  # complex grad of h wrt a(T)
            # a(T) = conj(sum_i beta_i E[T,i]) ; dh = Re(conj(gam_T) da_T) = Re(conj(gam_T) conj(E beta-variation))
            #   = Re(gam_T * E[T,i] * dbeta_i) ... -> complex grad wrt beta_i = sum_T conj(gam_T E[T,i])
            gb = np.conj(E).T @ np.conj(gam)  # m
            gb = np.conj(gb)
            # careful: d a_T = conj(E[T,i]) conj(d beta_i);  Re(conj(gam) d a) = Re(conj(gam) conj(E) conj(dbeta)) = Re(gam E dbeta)
            # => complex gradient wrt beta_i (d/dRe + i d/dIm) = conj(sum_T gam_T E[T,i])
            gb = np.conj(E.T @ gam)
            # phases: d a_T = conj(i E[T,i] beta_i Tmask[T,t] dph) ; dh = Re(gam E i beta Tmask dph) -> d h/d ph_it = Re(i beta_i sum_T gam_T E[T,i] Tmask[T,t])
            gph = np.real(1j * beta[:, None] * ((gam[:, None] * E).T @ self.Tmask))  # m x n
            gQb = self.r * np.abs(beta) ** (self.r - 2) * beta  # complex grad of |beta|^r
            gbeta = -gb / h + self.s * gQb / Q
            g[k:k + m] = gbeta.real; g[k + m:k + 2 * m] = gbeta.imag; k += 2 * m
            g[k:k + m * self.n] = (-gph / h).ravel(); k += m * self.n
        return ratio, h, Q, g

    def fobj(self, th):
        out = self.ratio_and_grad(th)
        if out is None or out[1] <= 1e-12:
            return 10.0, np.zeros_like(th)
        ratio, h, Q, g = out
        return -np.log(h) + self.s * np.log(Q), g

    def optimise(self, th, iters=400):
        res = minimize(self.fobj, th, jac=True, method='L-BFGS-B', options={'maxiter': iters, 'maxcor': 30})
        out = self.ratio_and_grad(res.x)
        return (out[0] if out else -np.inf), res.x

    def pack(self, d):
        th = []
        for j in self.S:
            beta, ph = d[j]
            th += list(beta.real) + list(beta.imag) + list(ph.ravel())
        return np.array(th)

    def if_block(self, j, scale=1.0):
        nu = self.nu; y = max(self.ystar[j - 1], 0.02) * scale
        m = self.na[j]
        beta = np.zeros(m, dtype=complex); ph = np.zeros((m, self.n))
        for k in range(min(m, nu)):
            beta[k] = y / nu
            ph[k, :] = 2 * np.pi * k / nu
        return beta, ph


def run(p, n, b, restarts, seed, S=None, natoms=4, verbose=True):
    s = (n + 1) / b
    F = (p - 1) // 2
    S = S or list(range(1, F + 1))
    na = {j: natoms for j in S}
    A = FA(p, n, s, S, na)
    rng = np.random.default_rng(seed)
    d0 = {j: A.if_block(j) for j in S}
    th0 = A.pack(d0)
    r0 = A.ratio_and_grad(th0)[0]
    if verbose:
        print(f"R_atom p={p} n={n} b={b} S'={S} natoms={natoms}: Gamma={A.G:.5f} y*={np.round(A.ystar,4)}  IF ratio {r0:.6f}", flush=True)
    best = (r0, th0); t0 = time.time()
    for k in range(restarts):
        kind = k % 5
        d = {}
        for j in S:
            beta, ph = A.if_block(j)
            if kind == 0:      # IF + noise
                beta = beta + 0.3 * abs(beta).max() * (rng.normal(size=len(beta)) + 1j * rng.normal(size=len(beta)))
                ph = ph + 0.5 * rng.normal(size=ph.shape)
            elif kind == 1:    # random atoms
                beta = abs(beta).max() * (rng.normal(size=len(beta)) + 1j * rng.normal(size=len(beta)))
                ph = rng.uniform(0, 2 * np.pi, ph.shape)
            elif kind == 2:    # cheap: two aligned atoms on one random feature, IF elsewhere
                if j == S[k // 5 % len(S)]:
                    y = max(A.ystar[j - 1], 0.02)
                    beta = np.zeros(len(beta), dtype=complex); beta[0] = beta[1] = y / 2
                    ph = rng.uniform(0, 2 * np.pi, ph.shape); ph[1] = ph[0] + np.pi
            elif kind == 3:    # single atom per feature + small rest
                beta = 0.05 * abs(beta).max() * (rng.normal(size=len(beta)) + 1j * rng.normal(size=len(beta)))
                beta[0] = max(A.ystar[j - 1], 0.02)
                ph = rng.uniform(0, 2 * np.pi, ph.shape)
            else:              # uneven moduli on IF block
                beta = beta * rng.uniform(0.3, 1.7, len(beta))
                ph = ph + 0.2 * rng.normal(size=ph.shape)
            d[j] = (beta, ph)
        th = A.pack(d)
        try:
            val, th2 = A.optimise(th)
        except Exception as e:
            print('fail', e); continue
        if val > best[0]:
            best = (val, th2)
        if verbose:
            print(f"  restart {k} kind {kind}: {val:.6f}   best {best[0]:.6f}  ({time.time()-t0:.0f}s)", flush=True)
    return A, best


if __name__ == '__main__':
    p, n, b = int(sys.argv[1]), int(sys.argv[2]), float(sys.argv[3])
    restarts, seed = int(sys.argv[4]), int(sys.argv[5])
    S = [int(v) for v in sys.argv[6:]] or None
    A, (val, th) = run(p, n, b, restarts, seed, S)
    np.save(f"fa_p{p}_n{n}_b{b}_s{seed}.npy", th)
    print(f"BEST {val:.6f}")
